CREATE OR REPLACE VIEW MARTS.VW_POLICY_DECISION_RECOMMENDATION AS
SELECT
  POLICY_ID,
  POLICY_LABEL,
  ADEQUACY_RATE AS SAFE_RECOVERY_PATH_RATE,
  GESTURE_ADEQUACY_RATE,
  HIGH_RISK_UNDER_RECOVERY_RATE,
  INTERNAL_COST_MID,
  DIRECT_ROOM_REFUND_VALUE,
  MANAGER_REVIEW_RATE,
  JOINT_GUARDRAIL_PASS_PROBABILITY,
  POLICY_SELECTION_PROBABILITY,
  EXECUTIVE_RECOMMENDATION,
  EVIDENCE_BOUNDARY
FROM MARTS.MART_POLICY_DECISION_SUMMARY
WHERE SELECTED_FOR_PILOT;

CREATE OR REPLACE VIEW MARTS.VW_POLICY_TRADEOFF AS
SELECT
  *
FROM MARTS.MART_POLICY_DECISION_SUMMARY
ORDER BY IFF(SELECTED_FOR_PILOT, 1, 0) DESC,
         INTERNAL_COST_MID;

CREATE OR REPLACE VIEW MARTS.VW_POLICY_SEGMENT_DIAGNOSTICS AS
SELECT *
FROM MARTS.MART_POLICY_SEGMENT_DIAGNOSTICS
WHERE NOT SUPPRESSED_SMALL_GROUP;

